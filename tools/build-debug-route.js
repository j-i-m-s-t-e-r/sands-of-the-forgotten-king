// Builds src/debug-route.js from the two playthrough lists in tests/, so the **debug jump
// always replays the same full-score route that `npm test` checks.
// Usage: node tools/build-debug-route.js        (run it whenever the playthrough lists change)
const fs = require("fs"), path = require("path");
const read = f => fs.readFileSync(path.join(__dirname, "..", "tests", f), "utf8").split("\n").map(l => l.trim()).filter(Boolean);
const commands = [...read("part1-cairo-to-valley.txt"), ...read("part2-pyramid-to-ending.txt")];
const js = "// Generated by tools/build-debug-route.js from the two playthrough lists in tests/.\n"
  + "// Developer only: leave this file out of the public build (it is a complete walkthrough).\n"
  + "const DEBUG_ROUTE = " + JSON.stringify(commands, null, 1) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "src", "debug-route.js"), js);
console.log(commands.length + " commands written to src/debug-route.js");
